// Как называется товар для того, кто на него смотрит.
//
// В 1С у товара два имени: служебное `name` («Датчик износа колодок 124-D»,
// имя номенклатуры) и `fullName` — применяемость, по которой клиент и
// подбирает деталь («Mercedes W124, W190 (длина 150мм) (передние)»).
//
// Клиенту служебное имя не показывается НИГДЕ: ни в каталоге, ни в корзине,
// ни в заказах и возвратах. Персоналу, в письме менеджеру и в самой 1С
// нужно именно оно, поэтому в базе хранятся оба.
//
// Применяемость пустая ровно у единиц товаров — тогда клиенту остаётся
// артикул, он и так стоит строкой выше во всех списках.

export function productTitle(
  product: { fullName?: string | null; name?: string | null },
  role?: string | null
): string {
  const full = product.fullName?.trim();
  if (full) return full;
  return role === "CLIENT" ? "" : product.name?.trim() ?? "";
}
