// Общие правила к паролю для обеих форм смены (свой пароль и сброс клиенту).
// Живут в lib, а не в route-файле: Next.js разрешает роутам экспортировать
// только обработчики и свои настройки, лишний экспорт валит сборку типов.
//
// Порог намеренно скромный: у большинства клиентов логин — это телефон, и
// строгие требования к сложности они просто не пройдут. Задача формы — дать
// уйти от общего пароля, выданного при импорте базы.
export const MIN_PASSWORD = 6;

// Возвращает текст ошибки или null, если пароль годится.
export function checkPassword(password: string): string | null {
  if (password.length < MIN_PASSWORD) {
    return `Пароль — минимум ${MIN_PASSWORD} символов`;
  }
  return null;
}
